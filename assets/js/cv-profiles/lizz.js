// Runs only when the lizz profile hash is active.
// Fixes hardcoded HTML elements (email, social links, nav logo) and sets
// Spanish as the default language before main.js initializes.
(function () {
    const urlParams = new URLSearchParams(window.location.search);
    if (urlParams.get('v') !== 'l1z2g3t') return;

    // Default to Spanish if the user has no saved language preference
    if (!localStorage.getItem('selected-lang')) {
        localStorage.setItem('selected-lang', 'es');
    }

    document.addEventListener('DOMContentLoaded', function () {
        // 1. Update hardcoded email text node
        const contactInfo = document.getElementById('home-contact-info');
        if (contactInfo) {
            contactInfo.querySelectorAll('.home__information').forEach(function (span) {
                if (span.querySelector('.bx-envelope')) {
                    // Remove ALL existing text nodes (there can be more than one)
                    Array.from(span.childNodes).forEach(function (node) {
                        if (node.nodeType === Node.TEXT_NODE) node.remove();
                    });
                    // Append exactly one clean text node with the correct email
                    span.appendChild(document.createTextNode(' lizethgont@gmail.com'));
                }
            });
        }

        // 2. Update nav logo name
        const navLogo = document.querySelector('.nav__logo');
        if (navLogo) navLogo.textContent = 'Lizeth González';

        // 3. Replace social links: LinkedIn only, no GitHub
        const socialContainer = document.querySelector('.social__container');
        if (socialContainer) {
            socialContainer.innerHTML =
                '<a class="social__link" href="https://www.linkedin.com/in/lizeth-gonzalez-torres-49b9a9205/" target="_blank">' +
                '<i class=\'bx bxl-linkedin-square social__icon\'></i> linkedin.com/in/lizeth-gonzalez-torres-49b9a9205' +
                '</a>';
        }

        // 4. Inject "Experiencia Complementaria" as a full section after #experience
        // Using the same HTML structure + CSS classes as the main experience section
        // so print.css renders it correctly.
        var expSection = document.getElementById('experience');
        if (expSection) {
            var compSection = document.createElement('section');
            compSection.className = 'experience section';
            compSection.id = 'lizz-complementary-section';

            var compTitle = document.createElement('h2');
            compTitle.className = 'section-title';
            compTitle.id = 'lizz-complementary-title';

            var compContainer = document.createElement('div');
            compContainer.className = 'experience__container bd-grid';

            var compEntry = document.createElement('div');
            compEntry.className = 'experience__content';
            compEntry.id = 'lizz-semarnat-entry';

            function renderSemarnat(lang) {
                var job = lizzProfile[lang] && lizzProfile[lang].experience.jobs[2];
                if (!job) return;
                compTitle.textContent = lang === 'es' ? 'Experiencia Complementaria' : 'Complementary Experience';
                compEntry.innerHTML =
                    '<div class="experience__time"><span class="experience__rounder"></span></div>' +
                    '<div class="experience__data bd-grid">' +
                        '<h3 class="experience__title">' + job.title + '</h3>' +
                        '<span class="experience__company">' + job.company + '</span>' +
                        '<p class="experience__description">' + job.description + '</p>' +
                    '</div>';
            }

            // Build and insert the complementary section
            compContainer.appendChild(compEntry);
            compSection.appendChild(compTitle);
            compSection.appendChild(compContainer);
            expSection.insertAdjacentElement('afterend', compSection);

            // Render with current language
            var activeLang = localStorage.getItem('selected-lang') || 'es';
            renderSemarnat(activeLang);

            // 5. Inject "Logros Relevantes" section after complementary section
            var logrosSection = document.createElement('section');
            logrosSection.className = 'experience section';
            logrosSection.id = 'lizz-logros-section';

            var logrosTitle = document.createElement('h2');
            logrosTitle.className = 'section-title';
            logrosTitle.id = 'lizz-logros-title';

            var logrosContainer = document.createElement('div');
            logrosContainer.className = 'experience__container bd-grid';

            var logrosEntry = document.createElement('div');
            logrosEntry.className = 'experience__content';
            logrosEntry.id = 'lizz-logros-entry';

            function renderLogros(lang) {
                var data = lizzProfile[lang] && lizzProfile[lang].logros;
                if (!data) return;
                logrosTitle.textContent = data.title;
                logrosEntry.innerHTML =
                    '<div class="experience__data bd-grid">' +
                        '<p class="experience__description">' +
                            data.items.map(function (item) { return '• ' + item; }).join('<br>') +
                        '</p>' +
                    '</div>';
            }

            logrosContainer.appendChild(logrosEntry);
            logrosSection.appendChild(logrosTitle);
            logrosSection.appendChild(logrosContainer);
            compSection.insertAdjacentElement('afterend', logrosSection);

            renderLogros(activeLang);

            // Keep both sections in sync when language is toggled
            var langBtn = document.getElementById('language-button');
            if (langBtn) {
                langBtn.addEventListener('click', function () {
                    setTimeout(function () {
                        var newLang = localStorage.getItem('selected-lang') || 'es';
                        renderSemarnat(newLang);
                        renderLogros(newLang);
                    }, 0);
                });
            }
        }
    });
})();
